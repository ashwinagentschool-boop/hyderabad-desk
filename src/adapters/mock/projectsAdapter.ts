export const projectsAdapter: ProjectsAdapter = {
  async list() {
    return remote('the project sheet', () => PROJECTS.map((p) => ({ ...p })));
  },

  async sync() {
    const projects = await remote('the project sheet', () =>
      PROJECTS.map((p) => ({ ...p })),
    );
    await statusAdapter.report({
      source: 'sheet',
      status: 'ok',
      ranAt: new Date().toISOString(),
      itemsCount: projects.length,
    });
    return projects;
  },
};
